// Stage 5 slice 5: works out every layout's spots on the bigger seas (starts, pack spots, respawn spots) for every
// ship count that uses them, and writes them to src/sim/seaSpotTable.ts, so a match only looks them up.
// Run from the repo root: node --experimental-strip-types shared/scripts/seaSpotTable.ts
import { writeFileSync } from "node:fs";
import { TUNING } from "../src/tuning.ts";
import { LAYOUT_IDS } from "../src/sim/layouts.ts";
import { searchSeaSpots, seaShipCounts } from "../src/sim/seaLayout.ts";

const round = (n: number) => Math.round(n * 10) / 10;
const rows: string[] = [];
for (const size of TUNING.seaSizes) {
  const sea = { width: size.width, height: size.height };
  for (const id of LAYOUT_IDS) {
    for (const ships of seaShipCounts(sea)) {
      const spots = searchSeaSpots(id, sea, ships);
      const list = (points: readonly { x: number; y: number }[]) => `[${points.map((p) => `[${round(p.x)}, ${round(p.y)}]`).join(", ")}]`;
      rows.push(`  "${id}:${sea.width}x${sea.height}:${ships}": {\n    starts: ${list(spots.starts)},\n    packSpots: ${list(spots.packSpots)},\n    respawns: ${list(spots.respawns)},\n  },`);
    }
  }
}
const out = new URL("../src/sim/seaSpotTable.ts", import.meta.url);
writeFileSync(out, `// Generated by shared/scripts/seaSpotTable.ts: do not edit by hand (run the script again after changing a layout,
// a sea size or the rules in seaLayout.ts; layouts.test.ts checks every row against the rules).
export const SEA_SPOT_TABLE: Readonly<Record<string, { starts: readonly (readonly [number, number])[]; packSpots: readonly (readonly [number, number])[]; respawns: readonly (readonly [number, number])[] }>> = {
${rows.join("\n")}
};
`);
console.log(`${rows.length} rows written`);
